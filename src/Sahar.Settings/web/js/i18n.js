let lang = 'ar';

/** 'ar' or 'en'. */
export function setLang(l) { lang = l === 'en' ? 'en' : 'ar'; }
export function getLang() { return lang; }

/** The string (or list) for key, with {vars} filled in. */
export function t(key, vars) {
  let v = strings[lang][key] ?? strings.ar[key];
  if (v === undefined) return key;
  if (vars && typeof v === 'string') for (const [k, x] of Object.entries(vars)) v = v.replaceAll(`{${k}}`, String(x));
  return v;
}
